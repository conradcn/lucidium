#!/usr/bin/env node
/**
 * Emit ``src/shared/generated/messages.ts`` — the type-level bridge
 * between a wire message type and its payload interface.
 *
 * Input is ``shared-schemas/message-map.json``, written by
 * ``scripts/codegen/export-schemas.py`` straight from the backend's own
 * ``C2S_PAYLOAD_BY_TYPE`` / ``S2C_PAYLOAD_BY_TYPE`` dispatch tables. We
 * deliberately do NOT re-derive the mapping from file names here: the
 * backend table is the single source of truth (Constitution V), and a
 * name-convention guess would silently disagree with it the day a
 * message type stops matching its class name.
 *
 * Runs after ``json2ts``, which produced one ``<Name>.schema.d.ts`` per
 * schema. If an expected interface is missing this script exits non-zero
 * rather than emit a file that will not compile.
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(HERE, "..", "..");
const MAP_PATH = join(REPO_ROOT, "shared-schemas", "message-map.json");
const OUT_DIR = join(HERE, "..", "src", "shared", "generated");
const OUT_PATH = join(OUT_DIR, "messages.ts");

if (!existsSync(MAP_PATH)) {
  console.error(
    `missing ${MAP_PATH}\n  Regenerate it with: python scripts/codegen/export-schemas.py`,
  );
  process.exit(1);
}

const map = JSON.parse(readFileSync(MAP_PATH, "utf8"));

/** Every payload interface referenced by either direction, deduped —
 *  a few models (none today, but nothing forbids it) could be shared. */
const modelNames = [
  ...new Set([...Object.values(map.c2s ?? {}), ...Object.values(map.s2c ?? {})]),
].sort();

const missing = [];
for (const name of modelNames) {
  const dts = join(OUT_DIR, `${name}.schema.d.ts`);
  if (!existsSync(dts)) {
    missing.push(name);
    continue;
  }
  // json2ts names the exported interface after the schema title. If a
  // title ever drifts from the class name the import below would be a
  // dangling name, so check for the declaration up front.
  const source = readFileSync(dts, "utf8");
  if (!new RegExp(`export (interface|type) ${name}\\b`).test(source)) {
    missing.push(`${name} (no exported \`${name}\` in ${name}.schema.d.ts)`);
  }
}
if (missing.length > 0) {
  console.error(
    "message-map.json references payload types with no generated " +
      `declaration:\n  ${missing.join("\n  ")}\n` +
      "  Run `python scripts/codegen/export-schemas.py` then `npm run codegen`.",
  );
  process.exit(1);
}

const imports = modelNames
  .map((name) => `import type { ${name} } from "./${name}.schema";`)
  .join("\n");

/** One `"wire/type": PayloadInterface;` line per entry, wire order. */
function members(table) {
  return Object.entries(table)
    .map(([messageType, model]) => `  "${messageType}": ${model};`)
    .join("\n");
}

const body = `/* eslint-disable */
/**
 * This file was automatically generated by frontend/scripts/gen-message-map.mjs.
 * DO NOT MODIFY IT BY HAND. Instead, modify the Pydantic dispatch tables in
 * backend/src/lucidium/api/messages.py, re-run
 * \`python scripts/codegen/export-schemas.py\`, then \`npm run codegen\`.
 */

${imports}

/** Client -> server: wire message type to its payload shape. */
export interface C2SPayloadByType {
${members(map.c2s ?? {})}
}

/** Server -> client: wire message type to its payload shape. */
export interface S2CPayloadByType {
${members(map.s2c ?? {})}
}

export type C2SMessageType = keyof C2SPayloadByType;
export type S2CMessageType = keyof S2CPayloadByType;
`;

writeFileSync(OUT_PATH, body, "utf8");
console.log(
  `wrote ${OUT_PATH} (${Object.keys(map.c2s ?? {}).length} c2s, ` +
    `${Object.keys(map.s2c ?? {}).length} s2c)`,
);
